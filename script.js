let num1 = +prompt("введите число  ");
let num2 = +prompt("введите число  ");
let sign = prompt("введите действие (+ , - , * , /) ");
switch(sign){
    case "+":
        alert(`${num1} + ${num2} = ${num1 + num2}`);
        break
        case "-":
        alert(`${num1} - ${num2} = ${num1 - num2}`);
        break
        case "*":
        alert(`${num1} * ${num2} = ${num1 * num2}`);
        break
        case "/":
            if(num2 === 0){
                alert("ошибка на 0 делить нельзя")
            }
            else{
                alert(`${num1} / ${num2} = ${num1 / num2}`);
            }
        break
        default: alert("нет такого знака")
}
